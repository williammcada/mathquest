// Builds public/games/shooter/world.js (Ironbreak v0.2.0) from the v0.1.0 blockout.
// Owner request 13 Oct 2026: level length +100% and enemy count +100%.
//  1. Second loop: sections B–E (x 800–5376) are repeated before the boss chamber,
//     with a MID2 checkpoint and guard in the repeated Transfer Lock.
//  2. Density: every non-mandatory robot gains a twin on the same platform/lane.
// Run: node scripts/build-ironbreak-world.mjs
import {writeFileSync} from 'node:fs';
import {WORLD as BASE} from '../public/games/shooter/world-blockout-0.2.js';

const LOOP_START=800,LOOP_END=5376,L=LOOP_END-LOOP_START;
const copy=v=>structuredClone(v);
const W={revision:'industrial-level-loop-0.3',world:{...BASE.world,width:BASE.world.width+L},sectors:[],layers:{}};

// Sectors: A B C D E | B2 C2 D2 E2 | F
for(const s of BASE.sectors){
  if(s.x0>=LOOP_END)continue;
  W.sectors.push({...copy(s),x1:Math.min(s.x1,LOOP_END)});
}
for(const s of BASE.sectors)if(s.x0>=LOOP_START&&s.x0<LOOP_END)W.sectors.push({...copy(s),id:s.id+'2',title:s.title+' II',x0:s.x0+L,x1:Math.min(s.x1,LOOP_END)+L});
for(const s of BASE.sectors)if(s.x0>=LOOP_END)W.sectors.push({...copy(s),x0:s.x0+L,x1:s.x1+L});

const MID2_X=BASE.layers.Checkpoints.find(c=>c.id==='MID').x+L;
const loopReset=x=>x<MID2_X?'MID':'MID2';
const ID_SUFFIX='-L2';
for(const [layer,items] of Object.entries(BASE.layers)){
  const out=[];
  for(const o of items){
    if(o.x>=LOOP_END){out.push({...copy(o),x:o.x+L,...(o.feet_x!==undefined?{feet_x:o.feet_x+L}:{}),...(o.spawn_x!==undefined?{spawn_x:o.spawn_x+L}:{})});continue;}
    const item=copy(o);
    if(layer==='Gates'&&o.type==='enemy_gate')item.enemy='H01';
    out.push(item);
  }
  for(const o of items){
    if(o.x<LOOP_START||o.x>=LOOP_END)continue;
    const c={...copy(o),id:o.id+ID_SUFFIX,x:o.x+L};
    if(c.feet_x!==undefined)c.feet_x+=L;
    if(c.spawn_x!==undefined)c.spawn_x+=L;
    if(c.reset_section)c.reset_section=loopReset(c.x);
    if(layer==='Checkpoints'&&o.id==='MID'){c.id='MID2';c.requires_enemy_defeated='H01'+ID_SUFFIX;}
    if(layer==='Gates'&&o.type==='enemy_gate'){c.id='MID2-GUARD-GATE';c.enemy='H01'+ID_SUFFIX;c.opens_when='H01'+ID_SUFFIX+' defeated';}
    if(layer==='Enemies'&&o.id==='H01')c.reset_section='MID';
    out.push(c);
  }
  W.layers[layer]=out.sort((a,b)=>a.x-b.x||String(a.id).localeCompare(String(b.id)));
}
// Keep the authored checkpoint order START, MID, MID2, BOSS.
W.layers.Checkpoints.sort((a,b)=>a.x-b.x);

// Density twins. A twin must stand on the same support (or water) with patrol room,
// stay clear of other robots, hazards and checkpoint spawns, and not cross a gate.
const supports=[...W.layers.Solids.filter(s=>s.supports_player),...W.layers.OneWay];
const barriers=[...W.layers.Gates.map(g=>g.x),...W.layers.Checkpoints.map(c=>c.spawn_x)];
const crosses=(a,b)=>barriers.some(x=>(a<x)!==(b<x));
function surfaceOK(e,x){
  const pad=(e.patrol_radius||0)+4;
  if(e.type==='skimmer')return W.layers.Water.some(w=>x-pad>=w.x&&x+e.w+pad<=w.x+w.w);
  if(['patrol','lobber','heavy'].includes(e.type))return supports.some(s=>s.y===e.feet_y&&x-pad>=s.x&&x+e.w+pad<=s.x+s.w);
  return x>=0&&x+e.w<=W.world.width;
}
const robots=W.layers.Enemies;
function clear(e,x){
  const box={x:x-10,y:e.y-10,w:e.w+20,h:e.h+20};
  const hit=r=>box.x<r.x+r.w&&box.x+box.w>r.x&&box.y<r.y+r.h&&box.y+box.h>r.y;
  return !robots.some(r=>r!==e&&hit(r))&&!W.layers.Hazards.some(h=>hit({x:h.x-16,y:h.y,w:h.w+32,h:h.h+8}))
    &&!W.layers.Checkpoints.some(c=>Math.abs(c.spawn_x-x)<200)&&!crosses(e.x,x);
}
const twins=[];
for(const e of [...robots]){
  if(e.mandatory||e.type==='boss')continue;
  const dx=[96,-96,128,-128,160,-160,64,-64,192,-192].find(d=>surfaceOK(e,e.x+d)&&clear(e,e.x+d));
  if(dx===undefined)throw Error(`No twin position for ${e.id}`);
  const t={...copy(e),id:e.id+'T',x:e.x+dx,twin_of:e.id};
  if(t.feet_x!==undefined)t.feet_x+=dx;
  robots.push(t);twins.push(t);
}
robots.sort((a,b)=>a.x-b.x||a.id.localeCompare(b.id));

const bossFloor=W.layers.Solids.find(s=>s.id==='BOSS-entry-lintel').x,trigger=W.layers.Gates.find(g=>g.type==='boss_trigger');
W.boss={entryX:bossFloor,gateX:trigger.x,triggerX:trigger.x+trigger.w,cameraMin:bossFloor+174,targetMin:bossFloor+214,targetMax:bossFloor+714};

const regular=robots.filter(e=>e.type!=='boss').length;
writeFileSync(new URL('../public/games/shooter/world.js',import.meta.url),
`// Generated by scripts/build-ironbreak-world.mjs from world-blockout-0.2.js. Do not edit by hand.
// Ironbreak v0.2.0: two loops of sections B–E, MID2 checkpoint, density twins. ${regular} regular robots.
export const WORLD = ${JSON.stringify(W)};
`);
console.log(`width ${W.world.width}; boss trigger ${W.boss.triggerX}; regular robots ${regular} (base ${BASE.layers.Enemies.filter(e=>e.type!=='boss').length}); twins ${twins.length}`);
