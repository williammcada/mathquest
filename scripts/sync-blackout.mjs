#!/usr/bin/env node
// Copies the canonical Blackout Protocol puzzle core into MathQuest as an ES module (approved
// Stage B decision D1: williammcada/blackout-protocol stays canonical for the core).
// Usage: node scripts/sync-blackout.mjs <path-to-blackout-protocol-checkout>
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { join, resolve } from 'node:path';
const source = resolve(process.argv[2] || '../blackout-protocol'), root = resolve(new URL('..', import.meta.url).pathname);
const core = readFileSync(join(source, 'src/core.js'), 'utf8');
const version = core.match(/const VERSION = '([^']+)'/)?.[1];
if (!version) throw Error('Could not read the core VERSION.');
let commit = null; try { commit = execFileSync('git', ['-C', source, 'rev-parse', 'HEAD']).toString().trim(); } catch {}
const sourceSha256 = createHash('sha256').update(core).digest('hex');
// The core is a UMD file; give it a local `module` so it exports into this ES module.
const out = `// GENERATED by scripts/sync-blackout.mjs from williammcada/blackout-protocol src/core.js. Do not edit.
// Core ${version} · commit ${commit} · source sha256 ${sourceSha256}
const module = { exports: {} };
${core}
const C = module.exports;
export default C;
export const { VERSION, DISTRICTS, RULES, EQUIPMENT, Run, generateBoard, powerState, verifySolved, rotMask, currentMask, isCorrect, hashSeed } = C;
`;
mkdirSync(join(root, 'public/games/blackout'), { recursive: true });
writeFileSync(join(root, 'public/games/blackout/core.js'), out);
writeFileSync(join(root, 'public/games/blackout/core.provenance.json'), JSON.stringify({ repository: 'williammcada/blackout-protocol', path: 'src/core.js', commit, version, sourceSha256 }, null, 2) + '\n');
console.log(JSON.stringify({ version, commit, sourceSha256 }));
