#!/usr/bin/env node
// Copies the verified Math Engine practice bundle into MathQuest and writes the teacher catalog.
// Usage: node scripts/sync-math-engine.mjs <path-to-MATH-ENGINE-checkout>
// The engine checkout must contain dist/math-engine-practice.js and its provenance JSON.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { join, resolve } from 'node:path';
const engineRoot = resolve(process.argv[2] || '../MATH-ENGINE'), root = resolve(new URL('..', import.meta.url).pathname);
const bundle = readFileSync(join(engineRoot, 'dist/math-engine-practice.js'));
const prov = JSON.parse(readFileSync(join(engineRoot, 'dist/math-engine-practice.provenance.json'), 'utf8'));
const sha = createHash('sha256').update(bundle).digest('hex');
if (sha !== prov.bundleSha256) throw Error('Engine bundle does not match its provenance hash.');
let commit = null; try { commit = execFileSync('git', ['-C', engineRoot, 'rev-parse', 'HEAD']).toString().trim(); } catch {}
const map = JSON.parse(readFileSync(join(engineRoot, 'docs/host-maps/mathquest-modules-v0.1.json'), 'utf8'));
mkdirSync(join(root, 'src/vendor'), { recursive: true });
writeFileSync(join(root, 'src/vendor/math-engine-practice.js'), bundle);
writeFileSync(join(root, 'src/vendor/math-engine.provenance.json'), JSON.stringify({ repository: 'williammcada/MATH-ENGINE', commit, ...prov }, null, 2) + '\n');
writeFileSync(join(root, 'src/vendor/mathquest-module-map.js'), `// GENERATED by scripts/sync-math-engine.mjs from MATH-ENGINE docs/host-maps/mathquest-modules-v0.1.json. Do not edit.\nexport const LEGACY_MODULE_MAP = Object.freeze(${JSON.stringify(map)});\n`);
const { default: E } = await import(join(root, 'src/vendor/math-engine-practice.js') + '?sync=' + Date.now());
const rows = E.catalog.map(e => [e.id, e.name, e.layer, e.gradeLabel, e.bankId || '', e.lessonLabel || '', e.lessonOrder ?? null]);
const courses = E.courses.map(c => ({ bankId: c.bankId, course: c.course, count: c.count }));
writeFileSync(join(root, 'public/engine-catalog.js'), `// GENERATED by scripts/sync-math-engine.mjs. Math Engine ${E.version} · content ${E.contentHash}. Do not edit.
export const ENGINE_VERSION = ${JSON.stringify(E.version)};
export const ENGINE_CONTENT_HASH = ${JSON.stringify(E.contentHash)};
export const ENGINE_COURSES = ${JSON.stringify(courses)};
// [id, name, layer, gradeLabel, bankId, lessonLabel, lessonOrder]
export const ENGINE_ROWS = ${JSON.stringify(rows)};
export const LEGACY_MODULE_MAP = ${JSON.stringify(map)};
`);
console.log(JSON.stringify({ engine: E.version, commit, contentHash: E.contentHash, bundleSha256: sha, rows: rows.length }));
